/**
 * 筋ID（または 'left-xxx' / 'right-xxx' 形式のメッシュID）から
 * 付着部・動きの役割・臨床ポイントを取得するヘルパー関数
 * @param {string} id
 * @returns {{ origin: string, insertion: string, action: string, clinical: string } | null}
 */
export function getAnatomyDetail(id) {
  if (!id || typeof id !== 'string') return null;
  const cleanId = id.trim();
  if (ANATOMY_DETAILS[cleanId]) {
    return ANATOMY_DETAILS[cleanId];
  }
  const baseId = cleanId.replace(/^(left|right)-/, '');
  return ANATOMY_DETAILS[baseId] || null;
}
